// こだわり条件（チェックボックス系）。noul なので確率がそのまま「入れる/入れない」の目安になる。
//
// yes / no は noul の criteria。これを書かないと、入力に何も手がかりが無い条件まで
// 0.4〜0.5 あたりに張り付いて「要確認」が増えてしまうので、
// 「言及も示唆も無ければ false」をはっきり書いて下に寄せている。
