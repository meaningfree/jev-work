/** Jev の /v1/systemone に投げる questions マップを組み立てる。 */
export function buildQuestions() {
  const questions = {};
  for (const axis of AXES) questions[axis.id] = axis.question;
  for (const flag of FLAGS) {
    questions[`flag_${flag.id}`] = {
      type: 'noul',
      instructions: flag.instructions,
      criteria: { true: flag.yes, false: NO_EVIDENCE },
    };
  }
  return questions;
}

/** 自由入力文を state に整形する。 */
export function buildState(text) {
  return {
    role: '不動産ポータルサイトで住み替え先を探している人のヒアリングメモ',
    note: '書かれていないことは推測してよいが、確信が持てない場合は確率を割り振ってよい。',
    hearing: text,
  };
}

/** 取引の種類（賃貸/購入）に応じて、表示する軸を絞る。 */
export function axesFor(torihiki) {
  return AXES.filter((axis) => !axis.appliesTo || axis.appliesTo === torihiki);
}
